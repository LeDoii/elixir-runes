"""Build docs/data.js from Devoir/Bindrune/Runes/runes.json (grid nodes -> pixels)."""
import json
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[2] / "Runes" / "runes.json"
DESC = Path(__file__).resolve().parent / "descriptions.json"
OUT = Path(__file__).resolve().parents[1] / "docs" / "data.js"
SERVER_OUT = Path(__file__).resolve().parents[1] / "server" / "lib" / "rune-data.js"

src = json.loads(SRC.read_text(encoding="utf-8"))
grid = src["grille"]


def px(c, r):
    return [160 + 48 * c, 58 + 33 * r]


descriptions = json.loads(DESC.read_text(encoding="utf-8"))
runes = []
for name, r in src["runes"].items():
    strokes = []
    for t in r["traits"]:
        pts = [px(c, row) for c, row in t["noeuds"]]
        if t["ferme"]:
            pts.append(pts[0])
        strokes.append({"name": t["nom"], "pts": pts})
    runes.append({"name": name, "glyph": r["glyphe"], "strokes": strokes, "sens": descriptions[name]})

xs = [p[0] for r in runes for st in r["strokes"] for p in st["pts"]]
ys = [p[1] for r in runes for st in r["strokes"] for p in st["pts"]]
data = {"strokeWidth": grid["epaisseur_px"], "bbox": [min(xs), min(ys), max(xs), max(ys)], "runes": runes}
OUT.write_text("window.RUNES = " + json.dumps(data, ensure_ascii=False) + ";\n", encoding="utf-8")
print(f"{len(runes)} runes -> {OUT}", file=sys.stderr)

# Server side (Pages Functions) validates shared bindrunes: it only needs each rune's anchor count.
anchor_counts = {r["name"]: len({tuple(p) for s in r["strokes"] for p in s["pts"]}) for r in runes}
SERVER_OUT.write_text(
    "// Generated by tools/build_data.py : do not edit." + chr(10) + "export const ANCHORS = " + json.dumps(anchor_counts, ensure_ascii=False) + ";" + chr(10),
    encoding="utf-8",
)
print(f"anchors -> {SERVER_OUT}", file=sys.stderr)
